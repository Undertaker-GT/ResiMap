const centrosMarkers = {};
let activeCentroPolygon = null;

Object.keys(centrosComerciales).forEach(id => {

  const centro = centrosComerciales[id];

  const icon = L.divIcon({
    className: "centro-marker",
    html: `
    <div class="centro-pin" id="centro-pin-${id}">
    🛍️
    </div>
    `,
    iconSize: [40,40],
    iconAnchor:[20,40]
  });

  const marker = L.marker(centro.coords,{icon}).addTo(map);

  marker.on("click",()=>{
    abrirModalCentro(id);
    mostrarAreaCentro(id);
  });

  centrosMarkers[id] = marker;

});

function mostrarAreaCentro(id){

  if(activeCentroPolygon){
    map.removeLayer(activeCentroPolygon);
    activeCentroPolygon = null;
  }

  if (activeSectorPolygon) {
    map.removeLayer(activeSectorPolygon);
    activeSectorPolygon = null;
  }

  if (activeGYMPolygon) {
    map.removeLayer(activeGYMPolygon);
    activeGYMPolygon = null;
  }

  if (activeSALONPolygon) {
    map.removeLayer(activeSALONPolygon);
    activeSALONPolygon = null;
  }

  if (activeCentroDeportivoPolygon) {
    map.removeLayer(activeCentroDeportivoPolygon);
    activeCentroDeportivoPolygon = null;
  }
  
  if (activeAreaInfantilPolygon) {
    map.removeLayer(activeAreaInfantilPolygon);
    activeAreaInfantilPolygon = null;
  }

  if (activepiscinaPolygon) {
    map.removeLayer(activepiscinaPolygon);
    activepiscinaPolygon = null;
  }

  if (activecolegioPolygon) {
    map.removeLayer(activecolegioPolygon);
    activecolegioPolygon = null;
  }

  const centro = centrosComerciales[id];

  activeCentroPolygon = L.polygon(centro.area,{
    color:"#f59e0b",
    weight:2,
    fillOpacity:0.25
  }).addTo(map);

  map.fitBounds(activeCentroPolygon.getBounds());
}

function abrirModalCentro(id){

  const centro = centrosComerciales[id];

  document.getElementById("centroTitulo").innerText = centro.nombre;

  const lista = document.getElementById("listaComercios");
  lista.innerHTML = "";

  centro.comercios.forEach((comercio,index)=>{

    const fotosHTML = comercio.fotos.map(f =>
      `<img src="${f}" alt="${comercio.nombre}">`
    ).join("");

    const item = document.createElement("div");

    item.className = "comercio-card";

    item.innerHTML = `

      <div class="comercio-carousel">
        ${fotosHTML}
      </div>

      <div class="comercio-info">

        <h4>${comercio.nombre}</h4>

        <div class="comercio-datos">

          <div>
            <i class="fas fa-phone"></i>
            ${comercio.telefono || "No disponible"}
          </div>

          <div>
            <i class="fas fa-clock"></i>
            ${comercio.horario || "Horario no disponible"}
          </div>

        </div>

        <button onclick="rutaComercio('${id}',${index})">
          <i class="fas fa-route"></i> Ir
        </button>

      </div>
    `;

    lista.appendChild(item);

  });

  document.getElementById("centroModal").classList.add("active");

}

function rutaComercio(centroId, comercioIndex){

  const comercio = centrosComerciales[centroId].comercios[comercioIndex];

  cerrarModalCentro();

  const destino = L.latLng(comercio.coords[0], comercio.coords[1]);

  destinationLatLng = destino;

  if (routingControl) {
    map.removeControl(routingControl);
  }

  routingControl = L.Routing.control({
    waypoints:[
      L.latLng(userLocation.lat,userLocation.lng),
      destino
    ],
    routeWhileDragging:false,
    router:L.Routing.osrmv1({
      serviceUrl:"https://router.project-osrm.org/route/v1"
    })
  }).addTo(map);

    ocultarPinesExcepto(centroId);
  document.getElementById("cancelRouteBtn").style.display = "flex";

  map.setView(areaSeleccionada.coords, 18);

}

function cerrarModalCentro(){
  document.getElementById("centroModal").classList.remove("active");
}

function actualizarZoomCentros() {

  const zoom = map.getZoom();

  Object.keys(centrosComerciales).forEach(id => {

    const pin = document.getElementById(`centro-pin-${id}`);

    if (!pin) return;

    pin.classList.remove("zoom-far", "zoom-mid", "zoom-near");

    if (zoom <= 15) {
      pin.classList.add("zoom-far");
    } 
    else if (zoom <= 17) {
      pin.classList.add("zoom-mid");
    } 
    else {
      pin.classList.add("zoom-near");
    }

  });

}

